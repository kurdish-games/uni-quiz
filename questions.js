/**
 * Builds a balanced 15-question run (5 Easy, 5 Medium, 5 Hard)
 * with randomized question selection and shuffled answer order!
 */
export function buildGameDeck(subjectId) {
  let pool = [];
  if (subjectId === 'mixed') {
    pool = [...QUESTION_BANK.psychology, ...QUESTION_BANK.morphology];
  } else {
    pool = [...(QUESTION_BANK[subjectId] || QUESTION_BANK.psychology)];
  }

  const pickByTier = (tier, count) => shuffle(pool.filter((q) => q.tier === tier)).slice(0, count);

  const selected = [
    ...pickByTier(1, 5),
    ...pickByTier(2, 5),
    ...pickByTier(3, 5),
  ];

  // Shuffle option order consistently across both English and Kurdish!
  return selected.map((q) => {
    const order = shuffle([0, 1, 2, 3]);
    return {
      ...q,
      options: order.map((i) => q.options[i]),
      answer: order.indexOf(q.answer),
      ku: {
        ...q.ku,
        options: order.map((i) => q.ku.options[i]),
      },
    };
  });
}

function shuffle(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
